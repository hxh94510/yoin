/* Deterministic synthetic reference, never real-user data. Run after model edits. */
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'..'),context={window:{}};
vm.createContext(context);
for(const file of ['data.js','interests.js','anime-catalog.js','anime.js'])vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),context,{filename:file});
const A=context.window.YOIN_ANIME,seed=731942,samples=8192;
let state=seed;
const rng=()=>((state=(Math.imul(1664525,state)+1013904223)>>>0)/4294967296);
const stats=new Map(context.window.YOIN_ANIME_CATALOG.titles.map(t=>[t.id,{mean:0,m2:0}]));
for(let n=1;n<=samples;n++)for(const r of A.rawMatch(A.shuffle(rng)).ranked){
  const p=stats.get(r.id),delta=r.score-p.mean;p.mean+=delta/n;p.m2+=delta*(r.score-p.mean);
}
const result={version:A.scoringVersion,key:A.calibrationKey,seed,samples,moments:Object.fromEntries([...stats].map(([id,p])=>[id,[+p.mean.toFixed(8),+Math.sqrt(p.m2/samples).toFixed(8)]]))};
const content='/* Generated by scripts/build-anime-calibration.cjs; synthetic casts, not audience statistics. */\nwindow.YOIN_ANIME_CALIBRATION = '+JSON.stringify(result)+';\n';
const target=path.join(root,'anime-calibration.js');
if(process.argv.includes('--check')){
  if(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==content)throw Error('Stale anime calibration: run node scripts/build-anime-calibration.cjs');
  console.log('PASS: reproducible calibration, 8192 non-repeating casts, 500 titles.');
}else{fs.writeFileSync(target,content);console.log('Generated anime-calibration.js:',samples,'casts, key',result.key);}
